/**
 * Log honeypot access for security alerting
 */
export async function logHoneypotAccess(ip: string, pathname: string, userAgent: string): Promise<void> {
  try {
    await prisma.securityLog.create({
      data: {
        ip,
        type: 'HONEYPOT_ACCESS',
        path: pathname,
        details: `Honeypot endpoint accessed! UA: ${userAgent}. This is likely an attacker probing the system.`,
        severity: 'CRITICAL',
      },
    })

    // Add IP to threat intelligence
    const { addThreatIndicator } = await import('./zero-trust-shield')
    addThreatIndicator({
      type: 'IP',
      value: ip,
      severity: 'CRITICAL',
      source: 'HONEYPOT',
      expiresAt: Date.now() + 7 * 24 * 60 * 60 * 1000, // 7 days
      metadata: { endpoint: pathname, userAgent },
    })

    console.error(`[HONEYPOT] CRITICAL: ${ip} accessed honeypot endpoint ${pathname}`)
  } catch (error) {
    console.error('[HONEYPOT] Failed to log access:', error)
  }
}

