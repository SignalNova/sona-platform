// 5. TRADING ALGORITHM PROTECTION
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * Protect trading algorithms from being reverse-engineered
 * Adds noise to trading-related responses to obscure the underlying logic
 */
export function protectTradingData(data: {
  price?: number
  volume?: number
  change?: number
  signal?: string
}): {
  price?: number
  volume?: number
  change?: number
  signal?: string
  _integrity: string
} {
  const result = { ...data }

  // Add micro-noise to prevent exact pattern matching
  // The noise is small enough not to affect trading but prevents exact algorithm reconstruction
  if (result.price) {
    const noiseFactor = (crypto.randomInt(0, 100) - 50) / 100000 // ±0.0005
    result.price = Math.round((result.price + result.price * noiseFactor) * 100) / 100
  }

  if (result.volume) {
    const noiseFactor = (crypto.randomInt(0, 100) - 50) / 10000 // ±0.005
    result.volume = Math.round((result.volume + result.volume * noiseFactor) * 100) / 100
  }

  // Add integrity hash to verify response hasn't been tampered with
  const integrityPayload = JSON.stringify(result) + Date.now()
  const integrity = crypto
    .createHmac('sha256', PLATFORM_FINGERPRINT)
    .update(integrityPayload)
    .digest('hex')
    .substring(0, 16)

  return { ...result, _integrity: integrity }
}

