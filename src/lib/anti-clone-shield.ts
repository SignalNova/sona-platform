// 2. API RESPONSE SIGNING & WATERMARKING
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * Sign API responses to prevent response tampering and enable clone detection
 * Each response contains a cryptographic signature that can be verified
 */
export function signApiResponse(data: any, endpoint: string, timestamp: number): {
  signedData: any
  signature: string
} {
  const payload = JSON.stringify(data)
  const message = `${endpoint}:${timestamp}:${payload}`

  const signature = crypto
    .createHmac('sha256', PLATFORM_FINGERPRINT)
    .update(message)
    .digest('hex')

  return {
    signedData: data,
    signature: signature.substring(0, 32), // Include partial signature for verification
  }
}

/**
 * Verify that an API response was generated by this platform instance
 */
export function verifyApiResponse(
  data: any,
  endpoint: string,
  timestamp: number,
  signature: string
): boolean {
  try {
    const payload = JSON.stringify(data)
    const message = `${endpoint}:${timestamp}:${payload}`
    const expectedSignature = crypto
      .createHmac('sha256', PLATFORM_FINGERPRINT)
      .update(message)
      .digest('hex')
      .substring(0, 32)

    const sigBuf = Buffer.from(signature, 'hex')
    const expBuf = Buffer.from(expectedSignature, 'hex')
    if (sigBuf.length !== expBuf.length) return false
    return crypto.timingSafeEqual(sigBuf, expBuf)
  } catch {
    return false
  }
}

