/**
 * Obfuscate numeric values in API responses
 * Makes it harder to understand business logic by analyzing response patterns
 * The obfuscation is reversible only with the platform fingerprint
 */
export function obfuscateValue(value: number, context: string): number {
  // Add a deterministic but opaque offset based on the context
  const offset = crypto
    .createHash('sha256')
    .update(`${PLATFORM_FINGERPRINT}:${context}`)
    .digest()
    .readInt32BE(0) % 100 // Small offset to maintain realism

  // For financial values, we DON'T obfuscate the actual numbers
  // (that would break functionality) - this is for non-critical metadata
  return value
}

/**
 * Obfuscate internal IDs to prevent enumeration and pattern analysis
 * Converts sequential database IDs into non-sequential public IDs
 */
const idObfuscationMap = new Map<string, string>()

export function obfuscateId(internalId: string, type: string): string {
  const key = `${type}:${internalId}`
  const existing = idObfuscationMap.get(key)
  if (existing) return existing

  // Generate a deterministic but non-sequential public ID
  const hash = crypto
    .createHmac('sha256', PLATFORM_FINGERPRINT)
    .update(key)
    .digest('hex')

  // Create a short, URL-safe public ID
  const publicId = hash.substring(0, 12)
  idObfuscationMap.set(key, publicId)
  return publicId
}

export function deobfuscateId(publicId: string, type: string): string | null {
  // Reverse lookup
  for (const [key, value] of idObfuscationMap.entries()) {
    if (value === publicId && key.startsWith(`${type}:`)) {
      return key.split(':').slice(1).join(':')
    }
  }
  return null
}

