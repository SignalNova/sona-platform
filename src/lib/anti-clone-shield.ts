// 4. ANTI-SCRAPING PROTECTION
// ═══════════════════════════════════════════════════════════════════════════════

interface ScrapingDetection {
  isScraping: boolean
  confidence: number
  patterns: string[]
}

const requestPatterns = new Map<string, {
  endpoints: Set<string>
  timestamps: number[]
  userAgents: Set<string>
  totalRequests: number
}>()

/**
 * Detect automated scraping of the platform
 * Analyzes request patterns to identify bots and scrapers
 */
export function detectScraping(ip: string, endpoint: string, userAgent: string): ScrapingDetection {
  let isScraping = false
  let confidence = 0
  const patterns: string[] = []

  const pattern = requestPatterns.get(ip) || {
    endpoints: new Set<string>(),
    timestamps: [],
    userAgents: new Set<string>(),
    totalRequests: 0,
  }

  pattern.endpoints.add(endpoint)
  pattern.timestamps.push(Date.now())
  pattern.userAgents.add(userAgent)
  pattern.totalRequests++

  // Keep only last 100 timestamps
  if (pattern.timestamps.length > 100) {
    pattern.timestamps = pattern.timestamps.slice(-50)
  }

  requestPatterns.set(ip, pattern)

  // Check 1: Rapid sequential endpoint access (crawling pattern)
  if (pattern.timestamps.length >= 10) {
    const recentTimestamps = pattern.timestamps.slice(-10)
    const timeSpan = recentTimestamps[recentTimestamps.length - 1] - recentTimestamps[0]
    if (timeSpan < 5000) { // 10 requests in 5 seconds
      confidence += 40
      patterns.push('RAPID_SEQUENTIAL_ACCESS')
      isScraping = true
    }
  }

  // Check 2: Systematic endpoint enumeration
  if (pattern.endpoints.size > 30) {
    confidence += 30
    patterns.push('ENDPOINT_ENUMERATION')
    isScraping = true
  }

  // Check 3: Multiple user agents from same IP
  if (pattern.userAgents.size > 5) {
    confidence += 25
    patterns.push('MULTIPLE_USER_AGENTS')
    isScraping = true
  }

  // Check 4: High total request volume
  if (pattern.totalRequests > 500) {
    confidence += 20
    patterns.push('HIGH_REQUEST_VOLUME')
    isScraping = true
  }

  // Check 5: Headless browser detection
  const headlessIndicators = [
    'headless', 'phantomjs', 'selenium', 'puppeteer',
    'playwright', 'chromium', 'webdriver', 'bot',
    'crawl', 'spider', 'scrape',
  ]
  const lowerUA = userAgent.toLowerCase()
  for (const indicator of headlessIndicators) {
    if (lowerUA.includes(indicator)) {
      confidence += 50
      patterns.push(`HEADLESS_BROWSER:${indicator}`)
      isScraping = true
      break
    }
  }

  return { isScraping, confidence: Math.min(100, confidence), patterns }
}

